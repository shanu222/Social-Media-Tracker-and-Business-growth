import fs from 'node:fs';
import PDFDocument from 'pdfkit';
import { BRAND } from '../brand.js';

/* Branded performance report: cover band, indicator gauges, trend and allocation charts,
   lists, plus the logo/CONFIDENTIAL watermark and contact footer on every page. */

const C = { ink: '#0f1b33', muted: '#5b6676', faint: '#8a95a5', line: '#dfe5ee', soft: '#f3f6fa', navy: BRAND.colors.navy, navy2: BRAND.colors.navy2, blue: BRAND.colors.blue, cyan: BRAND.colors.cyan, green: BRAND.colors.green, greenDark: BRAND.colors.greenDark, red: '#c2372f', amber: '#b07412' };
const SERIES = ['#1a5fe0', '#16b97a', '#12b5e8', '#7a3fb0', '#e0812a', '#c2372f', '#0b7f66', '#b03a6b'];
const fmt = (n, d = 0) => (n === null || n === undefined ? '—' : Number(n).toLocaleString('en-US', { maximumFractionDigits: d }));
const day = (d) => new Date((d instanceof Date ? d.toISOString() : String(d)).slice(0, 10) + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', year: 'numeric', timeZone: 'UTC' });
const iso = (d) => (d instanceof Date ? d.toLocaleDateString('en-CA', { timeZone: process.env.APP_TIMEZONE || 'Asia/Karachi' }) : String(d).slice(0, 10));
const short = (d) => new Date(iso(d) + 'T00:00:00Z').toLocaleDateString('en-GB', { day: 'numeric', month: 'short', timeZone: 'UTC' });
const hrs = (h) => (h === null || h === undefined ? '—' : h < 1 ? '<1 h' : h >= 48 ? `${Math.round((h / 24) * 10) / 10} d` : `${h} h`);

export function renderPerformancePdf(r, { generatedBy }) {
  return new Promise((resolve, reject) => {
    const title = r.mode === 'person' ? `Performance report — ${r.user.name}` : 'Team performance report';
    const doc = new PDFDocument({ size: 'A4', margins: { top: 56, bottom: 70, left: 48, right: 48 }, bufferPages: true, info: { Title: title, Author: BRAND.legal, Creator: BRAND.app } });
    const chunks = [];
    doc.on('data', (c) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
    const L = 48, W = doc.page.width - 96;
    const bottom = () => doc.page.height - 78;
    const hasLogo = fs.existsSync(BRAND.logo);
    const ensure = (h) => { if (doc.y + h > bottom()) { doc.addPage(); doc.y = 56; } };

    // Cover band
    const bandH = 150;
    const g = doc.linearGradient(0, 0, doc.page.width, bandH); g.stop(0, C.navy).stop(0.65, C.navy2).stop(1, '#0d3b6e');
    doc.rect(0, 0, doc.page.width, bandH).fill(g);
    const ac = doc.linearGradient(0, bandH - 4, doc.page.width, bandH); ac.stop(0, C.blue).stop(0.5, C.cyan).stop(1, C.green);
    doc.rect(0, bandH - 4, doc.page.width, 4).fill(ac);
    if (hasLogo) doc.image(BRAND.logo, L, 26, { width: 92, height: 92 });
    const tx = hasLogo ? L + 110 : L, tw = W - (tx - L);
    doc.fillColor('#9fd8ff').font('Helvetica-Bold').fontSize(9).text(BRAND.legal.toUpperCase(), tx, 28, { characterSpacing: 1, width: tw });
    doc.fillColor('#ffffff').font('Helvetica-Bold').fontSize(19).text(title, tx, 44, { width: tw });
    const sub = r.mode === 'person' && r.user.title ? r.user.title : null;
    doc.fillColor('#c9d6ea').font('Helvetica').fontSize(10);
    if (sub) doc.text(sub, tx, doc.y + 1, { width: tw });
    doc.text(`Period: ${day(r.range.from)} – ${day(r.range.to)}${r.product ? `  ·  Product: ${r.product.name}` : ''}`, tx, doc.y + 2, { width: tw });
    const now = new Date();
    doc.text(`Generated by ${generatedBy} on ${now.toLocaleDateString('en-GB', { day: 'numeric', month: 'long', year: 'numeric' })} at ${now.toLocaleTimeString('en-GB', { hour: '2-digit', minute: '2-digit', timeZone: process.env.APP_TIMEZONE || 'Asia/Karachi' })}`, tx, doc.y + 2, { width: tw });
    doc.y = bandH + 22;

    const heading = (t, s) => {
      ensure(70);
      doc.moveDown(0.5);
      const y = doc.y;
      doc.rect(L, y + 2, 4, 16).fill(C.blue);
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(13.5).text(t, L + 12, y, { width: W - 12 });
      if (s) doc.fillColor(C.muted).font('Helvetica').fontSize(9).text(s, L + 12, doc.y + 1, { width: W - 12 });
      doc.moveDown(0.6); doc.x = L;
    };

    // Ring gauge
    const gauge = (cx, cy, rad, value, color, label, sub) => {
      doc.save();
      doc.lineWidth(9).strokeColor('#e8edf4').circle(cx, cy, rad).stroke();
      if (value !== null && value !== undefined && value > 0) {
        const a0 = -Math.PI / 2, a1 = a0 + (Math.min(100, value) / 100) * Math.PI * 2;
        const steps = 60;
        doc.moveTo(cx + rad * Math.cos(a0), cy + rad * Math.sin(a0));
        for (let i = 1; i <= steps; i++) { const a = a0 + ((a1 - a0) * i) / steps; doc.lineTo(cx + rad * Math.cos(a), cy + rad * Math.sin(a)); }
        doc.lineWidth(9).lineCap('round').strokeColor(color).stroke();
      }
      doc.restore();
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(15).text(value === null || value === undefined ? '—' : `${value}%`, cx - rad, cy - 9, { width: rad * 2, align: 'center' });
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(9).text(label, cx - 60, cy + rad + 10, { width: 120, align: 'center' });
      if (sub) doc.fillColor(C.muted).font('Helvetica').fontSize(8).text(sub, cx - 60, cy + rad + 22, { width: 120, align: 'center' });
    };

    const bars = (rows, { valueKey, labelKey, unit = '', colorFor }) => {
      const rowH = 18, labelW = 150, max = Math.max(1, ...rows.map((x) => x[valueKey] || 0)), barW = W - labelW - 60;
      rows.forEach((x, i) => {
        ensure(rowH + 4);
        const y = doc.y;
        doc.fillColor(C.ink).font('Helvetica').fontSize(8.5).text(String(x[labelKey]), L, y + 4, { width: labelW - 8, lineBreak: false, ellipsis: true });
        const len = Math.max(2, ((x[valueKey] || 0) / max) * barW);
        doc.roundedRect(L + labelW, y + 3, len, rowH - 7, 3).fill(colorFor ? colorFor(x, i) : SERIES[i % SERIES.length]);
        doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(8.5).text(`${fmt(x[valueKey], 1)}${unit}`, L + labelW + len + 6, y + 4, { width: 60 });
        doc.y = y + rowH;
      });
      doc.moveDown(0.5);
    };

    // Hours as bars (left axis), completed tasks as a line (right axis)
    const columns = (points, { key, key2, label, label2 }) => {
      ensure(175);
      const x0 = L + 30, y0 = doc.y + 8, w = W - 64, h = 120;
      const maxB = Math.max(1, ...points.map((p) => p[key2] || 0));
      const maxL = Math.max(1, ...points.map((p) => p[key] || 0));
      for (let k = 0; k <= 4; k++) {
        const yy = y0 + h - (h * k) / 4;
        doc.moveTo(x0, yy).lineTo(x0 + w, yy).strokeColor(C.line).lineWidth(0.5).stroke();
        doc.fillColor(C.green).font('Helvetica').fontSize(7).text(fmt((maxB * k) / 4, 1), L - 6, yy - 4, { width: 32, align: 'right' });
        doc.fillColor(C.blue).text(fmt((maxL * k) / 4, 1), x0 + w + 4, yy - 4, { width: 28 });
      }
      const slot = w / points.length, bw = Math.min(22, slot * 0.6);
      const step = Math.max(1, Math.ceil(points.length / 10));
      points.forEach((p, i) => {
        const cx = x0 + slot * i + slot / 2;
        const hb = ((p[key2] || 0) / maxB) * h;
        if (hb > 0) doc.roundedRect(cx - bw / 2, y0 + h - hb, bw, hb, 2).fill('#9fe3c6');
        if (i % step === 0) doc.fillColor(C.faint).fontSize(7).text(short(p.start), cx - 22, y0 + h + 4, { width: 44, align: 'center' });
      });
      const pt = (p, i) => [x0 + slot * i + slot / 2, y0 + h - ((p[key] || 0) / maxL) * h];
      points.forEach((p, i) => { const [x, y] = pt(p, i); if (i === 0) doc.moveTo(x, y); else doc.lineTo(x, y); });
      doc.strokeColor(C.blue).lineWidth(1.8).stroke();
      points.forEach((p, i) => { const [x, y] = pt(p, i); doc.circle(x, y, 2.4).fill(C.blue); });
      const ly = y0 + h + 18;
      doc.rect(x0, ly + 2, 8, 8).fill('#9fe3c6'); doc.fillColor(C.muted).fontSize(8).text(label2, x0 + 12, ly + 1);
      doc.circle(x0 + 114, ly + 6, 3).fill(C.blue); doc.fillColor(C.muted).text(label, x0 + 122, ly + 1);
      doc.y = ly + 18; doc.x = L;
    };

    const list = (items, colorFor) => {
      items.forEach((it) => {
        const text = typeof it === 'string' ? it : it.text;
        ensure(30);
        const y = doc.y;
        const h = doc.font('Helvetica').fontSize(9.5).heightOfString(text, { width: W - 26 }) + 12;
        doc.roundedRect(L, y, W, h, 5).fill(C.soft);
        doc.rect(L, y, 3, h).fill(colorFor ? colorFor(it) : C.blue);
        doc.fillColor(C.ink).text(text, L + 14, y + 6, { width: W - 26 });
        doc.y = y + h + 5;
      });
    };
    const toneColor = (i) => (i.tone === 'good' ? C.green : i.tone === 'risk' ? C.red : i.tone === 'warn' ? C.amber : C.blue);

    const ind = r.mode === 'person' ? r.indicators : null;
    if (r.mode === 'person') {
      heading('Performance indicators', 'Measured from task outcomes and time logged on tasks');
      const cy = doc.y + 48, gap = W / 4;
      gauge(L + gap * 0.5, cy, 34, ind.completion_rate, C.blue, 'Task completion', `${ind.completed} of ${ind.assigned} tasks`);
      gauge(L + gap * 1.5, cy, 34, ind.on_time_rate, C.green, 'On-time completion', `${ind.late} late`);
      gauge(L + gap * 2.5, cy, 34, ind.avg_progress, C.cyan, 'Work progress', `${ind.in_progress + ind.not_started} active tasks`);
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(20).text(`${fmt(ind.hours, 1)} h`, L + gap * 3, cy - 20, { width: gap, align: 'center' });
      doc.fillColor(C.muted).font('Helvetica').fontSize(8.5).text(`avg ${hrs(ind.avg_completion_hours)} per task`, L + gap * 3, cy + 4, { width: gap, align: 'center' });
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(9).text('Time on tasks', L + gap * 3, cy + 44, { width: gap, align: 'center' });
      doc.y = cy + 74;
      const p = r.previous;
      const cmp = (a, b, u = '%') => (a === null || b === null ? 'no earlier data' : `${a - b >= 0 ? '+' : ''}${Math.round((a - b) * 10) / 10}${u}`);
      doc.fillColor(C.muted).font('Helvetica').fontSize(8.5).text(`Compared with ${day(r.previousRange.from)} – ${day(r.previousRange.to)}: completion ${cmp(ind.completion_rate, p.completion_rate)}, on-time ${cmp(ind.on_time_rate, p.on_time_rate)}, completed tasks ${cmp(ind.completed, p.completed, '')}, hours ${cmp(ind.hours, p.hours, ' h')}.`, L, doc.y, { width: W });
      doc.moveDown(0.6);

      if (r.insights?.length) { heading('Summary'); list(r.insights, toneColor); }
      heading('Productivity trend', `Completed tasks and hours per ${r.trend.size}`);
      columns(r.trend.points, { key: 'completed', key2: 'hours', label: 'Tasks completed', label2: 'Hours logged' });
      if (r.timeByProduct.length) { heading('Time by product'); bars(r.timeByProduct, { valueKey: 'hours', labelKey: 'name', unit: ' h' }); }
      if (r.tasksByProduct.length) { heading('Tasks by product', 'Assigned in the period'); bars(r.tasksByProduct, { valueKey: 'assigned', labelKey: 'name' }); }
      if (r.user.role === 'admin' || r.management.tasks_created) {
        heading('Management activity');
        bars([
          { k: 'Tasks created', v: r.management.tasks_created }, { k: 'Created tasks completed', v: r.management.created_tasks_completed },
          { k: 'Messages sent', v: r.management.messages_sent }, { k: 'Announcements', v: r.management.announcements }, { k: 'Task comments', v: r.management.comments },
        ], { valueKey: 'v', labelKey: 'k' });
      }
      if (r.activity.length) { heading('Work activity'); bars(r.activity, { valueKey: 'count', labelKey: 'label' }); }
      if (r.achievements.length) { heading('Completed work'); list(r.achievements.map((a) => `${a.title} — ${a.product_name}, ${short(a.completed_at)}${a.on_time ? '' : ' (late)'}`), (s) => (s.endsWith('(late)') ? C.amber : C.green)); }
      if (r.active.length) { heading('Ongoing work'); list(r.active.map((a) => `${a.title} — ${a.product_name}, ${a.progress}% done${a.due_date ? `, due ${short(a.due_date)}` : ''}`), (s) => (/due/.test(s) && r.active.find((x) => s.startsWith(x.title))?.overdue ? C.red : C.blue)); }
      if (r.attention.length) { heading('Needs attention'); list(r.attention.map((a) => a.text), () => C.red); }
    } else {
      heading('Team overview', `${fmt(r.team.completed)} of ${fmt(r.team.assigned)} tasks completed (${r.team.completion_rate ?? '—'}%), ${fmt(r.team.hours, 1)} h logged, ${fmt(r.team.overdue)} overdue`);
      if (r.insights?.length) list(r.insights, toneColor);
      heading('Completion and on-time rate by person');
      const people = r.people.filter((p) => p.role === 'admin' || p.indicators.assigned > 0 || p.indicators.hours > 0);
      people.forEach((p) => {
        ensure(46);
        const y = doc.y;
        doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(9.5).text(p.name, L, y, { width: 150 });
        doc.fillColor(C.muted).font('Helvetica').fontSize(8).text(p.title || (p.role === 'admin' ? 'Admin' : 'Team member'), L, y + 12, { width: 150 });
        const bw = W - 210;
        [[p.indicators.completion_rate, C.blue, 'Completion'], [p.indicators.on_time_rate, C.green, 'On time']].forEach(([v, col, lab], k) => {
          const yy = y + k * 15;
          doc.roundedRect(L + 160, yy + 1, bw, 9, 4).fill('#e8edf4');
          if (v) doc.roundedRect(L + 160, yy + 1, Math.max(4, (bw * v) / 100), 9, 4).fill(col);
          doc.fillColor(C.ink).font('Helvetica').fontSize(8).text(`${lab} ${v ?? '—'}${v === null ? '' : '%'}`, L + 165 + bw, yy, { width: 60 });
        });
        doc.y = y + 38;
      });
      heading('Workload and time', 'Open tasks and hours per person');
      bars(people.map((p) => ({ name: p.name, open: p.indicators.not_started + p.indicators.in_progress })), { valueKey: 'open', labelKey: 'name' });
      bars(people.map((p) => ({ name: p.name, hours: p.indicators.hours })), { valueKey: 'hours', labelKey: 'name', unit: ' h', colorFor: () => C.green });
      heading('Team trend', `Completed tasks and hours per ${r.trend.size}`);
      columns(r.trend.points, { key: 'completed', key2: 'hours', label: 'Tasks completed', label2: 'Hours logged' });
      if (r.timeByProduct.length) { heading('Time by product'); bars(r.timeByProduct, { valueKey: 'hours', labelKey: 'name', unit: ' h' }); }
      heading('Indicator details');
      const cols = [['Person', 0.24], ['Assigned', 0.1], ['Done', 0.09], ['Overdue', 0.1], ['Completion', 0.12], ['On time', 0.11], ['Avg time', 0.12], ['Hours', 0.12]];
      ensure(40);
      let y = doc.y;
      doc.rect(L, y, W, 20).fill(C.navy);
      let x = L;
      cols.forEach(([h, w]) => { doc.fillColor('#fff').font('Helvetica-Bold').fontSize(8).text(h, x + 5, y + 6, { width: w * W - 10, lineBreak: false }); x += w * W; });
      y += 20;
      people.forEach((p, i) => {
        if (y + 20 > bottom()) { doc.addPage(); y = 56; }
        if (i % 2) doc.rect(L, y, W, 20).fill(C.soft);
        const v = [p.name, p.indicators.assigned, p.indicators.completed, p.indicators.overdue, p.indicators.completion_rate === null ? '—' : `${p.indicators.completion_rate}%`, p.indicators.on_time_rate === null ? '—' : `${p.indicators.on_time_rate}%`, hrs(p.indicators.avg_completion_hours), `${p.indicators.hours} h`];
        x = L;
        cols.forEach(([, w], k) => { doc.fillColor(k === 3 && p.indicators.overdue ? C.red : C.ink).font(k === 0 ? 'Helvetica-Bold' : 'Helvetica').fontSize(8.5).text(String(v[k]), x + 5, y + 6, { width: w * W - 10, lineBreak: false, ellipsis: true }); x += w * W; });
        y += 20;
      });
      doc.y = y + 10;
    }

    ensure(60);
    doc.moveDown(0.8);
    doc.fillColor(C.faint).font('Helvetica').fontSize(8).text('Indicators: completion rate = completed ÷ assigned tasks; on-time rate = completed by the due date ÷ completed (tasks without a due date count as on time); work progress = average reported progress of active tasks; hours = time logged on tasks.', L, doc.y, { width: W });

    const range = doc.bufferedPageRange();
    for (let i = range.start; i < range.start + range.count; i++) {
      doc.switchToPage(i);
      doc.page.margins.bottom = 0;
      const cx = doc.page.width / 2, cyy = doc.page.height / 2 + 30;
      doc.save();
      if (hasLogo) { doc.opacity(0.04); doc.image(BRAND.logo, cx - 140, cyy - 140, { width: 280, height: 280 }); }
      doc.opacity(0.055).fillColor(C.navy).font('Helvetica-Bold').fontSize(30);
      doc.rotate(-35, { origin: [cx, cyy] });
      doc.text('RESILIENCE TECHNOLOGIES LABS', cx - 300, cyy - 16, { width: 600, align: 'center', lineBreak: false });
      doc.fontSize(15).text('CONFIDENTIAL  ·  GROWTH DESK FOR RTL', cx - 300, cyy + 22, { width: 600, align: 'center', characterSpacing: 3, lineBreak: false });
      doc.restore();
      const fy = doc.page.height - 50;
      doc.moveTo(L, fy - 8).lineTo(L + W, fy - 8).strokeColor(C.line).lineWidth(0.7).stroke();
      if (hasLogo) doc.image(BRAND.logo, L, fy - 2, { width: 22, height: 22 });
      doc.fillColor(C.ink).font('Helvetica-Bold').fontSize(8).text(`${BRAND.app}  ·  ${BRAND.legal}`, L + 28, fy - 1, { width: W - 120, lineBreak: false });
      doc.fillColor(C.muted).font('Helvetica').fontSize(7.5).text(`CEO ${BRAND.ceo}  ·  ${BRAND.email}  ·  ${BRAND.phone}  ·  ${BRAND.website}`, L + 28, fy + 10, { width: W - 120, lineBreak: false });
      doc.fillColor(C.muted).font('Helvetica').fontSize(8).text(`Page ${i + 1} of ${range.count}`, L + W - 90, fy + 3, { width: 90, align: 'right', lineBreak: false });
    }
    doc.end();
  });
}
